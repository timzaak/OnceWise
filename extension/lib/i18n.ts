const CATALOGS: Record<Locale, Catalog> = { en, zh };

let currentLocale: Locale | null = null;

function detectLocale(): Locale {
  // browser.i18n is available in SW and extension pages; navigator covers odd hosts (tests, jsdom)
  try {
    const ui = browser.i18n?.getUILanguage?.();
    if (typeof ui === 'string' && ui.toLowerCase().startsWith('zh')) return 'zh';
  } catch {
    // not in an extension context
  }
  if (typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('zh')) return 'zh';
  return 'en';
}

export function getLocale(): Locale {
  if (currentLocale === null) currentLocale = detectLocale();
  return currentLocale;
}

/** Test hook: pin the catalog instead of relying on host language detection. */
export function setLocale(locale: Locale): void {
  currentLocale = locale;
}

// {placeholder} interpolation — params values are strings/numbers and are inserted verbatim
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  let text: string = (CATALOGS[getLocale()] ?? en)[key] ?? en[key];
  if (params !== undefined) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function statusLabel(status: 'draft' | 'enabled' | 'paused'): string {
  return t(`flow.status.${status}` as MessageKey);
}
